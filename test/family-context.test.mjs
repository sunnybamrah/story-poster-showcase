test('per-story grown-ups retain stable identities and leave the saved family untouched', () => {
  const base = structuredClone(family);
  base.cast = lockedCast(base);
  base.cast.push({ ...structuredClone(base.cast.find(person => person.role === 'grown-up')), id: 'grown-up-two', label: 'the second grown-up' });
  base.storyPeople = [{ castId: 'grown-up-one', storyName: 'Dad' }, { castId: 'grown-up-two', storyName: 'Mom' }];
  base.parentLabel = 'Dad and Mom';
  const original = structuredClone(base);
  const selected = buildKitRecord(base, { kitContext: { selectedGrownUpIds: ['grown-up-two'], focusPersonId: 'grown-up-two' } });
  assert.deepEqual(selected.cast.map(person => person.id), ['child', 'grown-up-two']);
  assert.equal(selected.parentLabel, 'Mom');
  assert.equal(learningActor(selected).storyName, 'Mom');
  assert.deepEqual(selected.storyPeople, [{ castId: 'grown-up-two', storyName: 'Mom' }]);
  assert.ok(pictureCast(selected, moves[0], { scene: 'child beside the parent' }).some(person => person.id === 'grown-up-two'));
  assert.deepEqual(base, original);
  assert.equal(buildKitRecord(base).parentLabel, 'Dad and Mom');
  assert.equal(Object.hasOwn(buildKitRecord(base).kitContext, 'selectedGrownUpIds'), false);
  assert.throws(() => buildKitRecord(base, { kitContext: { selectedGrownUpIds: ['grown-up-two'], focusPersonId: 'grown-up-one' } }), /must join/);
  for (const ids of [[], ['stranger'], ['grown-up-one', 'grown-up-one']]) assert.throws(() => buildKitRecord(base, { kitContext: { selectedGrownUpIds: ids } }));
});
